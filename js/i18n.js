const LINGSCOUT_LANG_NAMES = { es: "Español", en: "English", fr: "Français", it: "Italiano", de: "Deutsch", pt: "Português" };

function t(key) {
  const lang = localStorage.getItem('lingscout-lang') || 'es';
  return (LINGSCOUT_TRANSLATIONS[lang] && LINGSCOUT_TRANSLATIONS[lang][key]) || LINGSCOUT_TRANSLATIONS.es[key] || key;
}

function aplicarTraducciones() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
  });
  const lang = localStorage.getItem('lingscout-lang') || 'es';
  document.documentElement.setAttribute('lang', lang);
}

document.addEventListener('DOMContentLoaded', () => {
  aplicarTraducciones();
  const selector = document.getElementById('lang-selector');
  if (selector) {
    const actual = localStorage.getItem('lingscout-lang') || 'es';
    selector.value = actual;
    selector.addEventListener('change', () => {
      localStorage.setItem('lingscout-lang', selector.value);
      aplicarTraducciones();
    });
  }
});
