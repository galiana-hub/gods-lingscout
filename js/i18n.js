function t(key) {
  const lang = localStorage.getItem('lingscout-lang') || 'es';
  return (LINGSCOUT_TRANSLATIONS[lang] && LINGSCOUT_TRANSLATIONS[lang][key]) || LINGSCOUT_TRANSLATIONS.es[key] || key;
}

// "análisis" con la forma plural correcta (polaco y ruso tienen una forma extra para 2-4)
function pluralAnalisis(n) {
  const lang = localStorage.getItem('lingscout-lang') || 'es';
  if (lang === 'ru') {
    const m10 = n % 10, m100 = n % 100;
    if (m10 === 1 && m100 !== 11) return t('ui.analisisUno');
    if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return t('ui.analisisPocos');
    return t('ui.analisisVarios');
  }
  if (lang === 'pl') {
    const m10 = n % 10, m100 = n % 100;
    if (n === 1) return t('ui.analisisUno');
    if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return t('ui.analisisPocos');
    return t('ui.analisisVarios');
  }
  return n === 1 ? t('ui.analisisUno') : t('ui.analisisVarios');
}

