// Botones tipo casilla (varios a la vez). "seleccion" es un Set que se actualiza al marcar/desmarcar
function construirChipsToggle(contenedorId, codigos, prefijoClave, seleccion) {
  const cont = document.getElementById(contenedorId);
  cont.innerHTML = '';
  codigos.forEach(codigo => {
    const label = document.createElement('label');
    label.className = 'chip chip-toggle';
    const input = document.createElement('input');
    input.type = 'checkbox';
    input.value = codigo;
    input.checked = seleccion.has(codigo);
    label.classList.toggle('on', input.checked);
    input.addEventListener('change', () => {
      if (input.checked) seleccion.add(codigo); else seleccion.delete(codigo);
      label.classList.toggle('on', input.checked);
    });
    const texto = document.createElement('span');
    texto.textContent = t(prefijoClave + codigo);
    label.append(input, texto);
    cont.appendChild(label);
  });
}

function aplicarTraducciones() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const txt = t(el.getAttribute('data-i18n-title'));
    el.setAttribute('title', txt);
    el.setAttribute('aria-label', txt);
  });
  const lang = localStorage.getItem('lingscout-lang') || 'es';
  document.documentElement.setAttribute('lang', LINGSCOUT_LOCALES[lang] || lang);
  document.documentElement.setAttribute('dir', LINGSCOUT_RTL.includes(lang) ? 'rtl' : 'ltr');
}

