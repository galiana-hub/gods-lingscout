function escaparHtml(texto) {
  return String(texto).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
}

// Etiqueta personalizada: sin "#", sin espacios (se sustituyen por _), en minúsculas y máx. 30 caracteres
function normalizarTag(raw) {
  return String(raw).trim().replace(/^#+/, '').trim().replace(/\s+/g, '_').toLocaleLowerCase().slice(0, 30);
}

function etiquetaAccion(codigo) {
  return LINGSCOUT_ACCIONES.includes(codigo) ? t('jf.acc_' + codigo) : codigo;
}

function htmlAcciones(lista) {
  if (!lista || !lista.length) return '';
  return '<div class="chip-list">' + lista.map(c => `<span class="chip chip-accion">${escaparHtml(etiquetaAccion(c))}</span>`).join('') + '</div>';
}

function htmlTags(lista) {
  if (!lista || !lista.length) return '';
  return '<div class="chip-list">' + lista.map(x => `<span class="chip chip-tag">#${escaparHtml(normalizarTag(x))}</span>`).join('') + '</div>';
}

